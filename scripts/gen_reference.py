#!/usr/bin/env python3
"""Generate the reference sections of docs/cli.md, docs/api.md, docs/config.md
and docs/safety.md.

The facts come from the code, never from scraped terminal output:

* CLI commands, options, defaults and help: the typer app, introspected;
* exit codes: ``agentconnect.cli_support.EXIT_CODES``;
* ``--json`` shapes: ``agentconnect.cli_json.SCHEMAS`` (the CLI tests check
  real output against the same shapes);
* local API routes: ``agentconnect.runtime.api.ROUTE_SPECS`` (the server is built from
  that table) and ``API_ERRORS``;
* config keys: ``agentconnect.config.CONFIG_KEYS`` and the ``Config`` dataclass;
* safety settings: ``agentconnect.policy.KNOBS``.

Each generated section sits between ``<!-- generated:NAME:start -->`` and
``<!-- generated:NAME:end -->`` in its doc. Prose outside the markers is
hand-written and left alone.

usage: uv run --all-packages python scripts/gen_reference.py [--check]
(``just docs-gen`` writes; ``--check`` fails when the docs are stale.)
"""

from __future__ import annotations

import dataclasses
import sys
from collections.abc import Callable, Iterator, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any, cast

import typer
import typer.core
import typer.main

from agentconnect import cli, cli_json, cli_support, config, policy
from agentconnect.runtime import api
from agentconnect.shapes import Opt

REPO = Path(__file__).resolve().parents[1]
NOTICE = "This section is generated by `just docs-gen`. Edit the code, not this text."


# -- markdown helpers -------------------------------------------------------------------


def cell(text: str) -> str:
    """Text safe inside a table cell."""
    return " ".join(text.split()).replace("|", "\\|")


def table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(cell(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def fence(text: str, lang: str = "text") -> str:
    return f"```{lang}\n{text}\n```"


def first_sentence(text: str) -> str:
    """The first sentence of ``text``, ending in one period."""
    flat = " ".join(text.split())
    head, dot, _ = flat.partition(". ")
    return (head if dot else flat).rstrip(".") + "."


def shape_text(shape: Any, indent: int = 0) -> str:
    """A shape (``agentconnect.shapes``) as indented, JSON-like text."""
    if isinstance(shape, Opt):
        return f"{shape_text(shape.inner, indent)} | null"
    if isinstance(shape, list):
        return f"[{shape_text(shape[0], indent)}]"
    if isinstance(shape, dict):
        pad = " " * (indent + 2)
        body = ",\n".join(
            f'{pad}"{k.removesuffix("?")}"{"?" if k.endswith("?") else ""}: '
            f"{shape_text(v, indent + 2)}"
            for k, v in shape.items()
        )
        return "{\n" + body + "\n" + " " * indent + "}"
    return str(shape)


# -- CLI --------------------------------------------------------------------------------


@dataclass(frozen=True)
class CliCommand:
    path: tuple[str, ...]
    command: typer.core.TyperGroup | typer.core.TyperCommand
    usage: str

    @property
    def name(self) -> str:
        return " ".join(self.path)

    @property
    def human(self) -> bool:
        return cli_support.HUMAN_ONLY_HELP in (self.command.help or "")

    @property
    def local(self) -> bool:
        return cli_support.LOCAL_ONLY_HELP in (self.command.help or "")

    @property
    def token(self) -> str:
        return "**human**" if self.human else "**local**" if self.local else "api"

    @property
    def help(self) -> str:
        text = (self.command.help or "").replace(cli_support.HUMAN_ONLY_HELP, "")
        text = text.replace(cli_support.LOCAL_ONLY_HELP, "")
        return "\n\n".join(" ".join(p.split()) for p in text.split("\n\n") if p.strip()).strip()


def _usage_pieces(command: typer.core.TyperCommand) -> list[str]:
    pieces = ["[OPTIONS]"]
    for arg in command.params:
        if isinstance(arg, typer.core.TyperArgument):
            name = (arg.name or "").upper()
            pieces.append(name if arg.required else f"[{name}]")
    return pieces


def walk_cli(app: typer.Typer = cli.app) -> Iterator[CliCommand]:
    """Every command, depth first in definition order. A group that runs on its
    own (``groups`` lists, ``approvals`` lists) is a command too."""
    root = cast("typer.core.TyperGroup", typer.main.get_command(app))
    root_ctx = typer.Context(root, info_name="agentconnect")

    def visit(
        command: typer.core.TyperGroup | typer.core.TyperCommand,
        ctx: typer.Context,
        path: tuple[str, ...],
    ) -> Iterator[CliCommand]:
        is_group = isinstance(command, typer.core.TyperGroup)
        pieces = ["[OPTIONS]", "COMMAND", "[ARGS]..."] if is_group else _usage_pieces(command)
        usage = " ".join([ctx.command_path, *pieces])
        if path and (not is_group or command.invoke_without_command):
            yield CliCommand(path, command, usage)
        if is_group:
            for name in command.list_commands(ctx):
                child = command.get_command(ctx, name)
                if not isinstance(child, typer.core.TyperGroup | typer.core.TyperCommand):
                    continue
                child_ctx = typer.Context(child, info_name=name, parent=ctx)
                yield from visit(child, child_ctx, (*path, name))

    yield from visit(root, root_ctx, ())


def _option_type(option: typer.core.TyperOption) -> str:
    if option.is_flag:
        return "flag"
    kind = option.type
    name = {"str": "text", "int": "integer", "float": "number"}.get(str(kind.name), str(kind.name))
    low, high = getattr(kind, "min", None), getattr(kind, "max", None)
    if low is not None or high is not None:
        name = f"integer {low if low is not None else ''}..{high if high is not None else ''}"
    return f"{name}, repeatable" if option.multiple else name


def _option_default(option: typer.core.TyperOption) -> str:
    if option.required:
        return "required"
    if option.is_flag:
        return "on" if option.default else "off"
    if option.default is None or option.default == ():
        return "none"
    return f"`{option.default}`"


def _options(command: CliCommand) -> list[typer.core.TyperOption]:
    return [
        p
        for p in command.command.params
        if isinstance(p, typer.core.TyperOption) and p.name != "help"
    ]


def _arguments(command: CliCommand) -> list[typer.core.TyperArgument]:
    return [p for p in command.command.params if isinstance(p, typer.core.TyperArgument)]


def render_cli_commands(app: typer.Typer = cli.app) -> str:
    commands = list(walk_cli(app))
    summary = table(
        ["Command", "Token", "What it does"],
        [
            (
                f"`{c.name}`",
                c.token,
                first_sentence(c.help),
            )
            for c in commands
        ],
    )
    parts = [
        NOTICE,
        summary,
        "Token: the commands marked human use the human token and are decisions for "
        "a person. Never run them on the human's behalf. The commands marked local use "
        "no token and no API: they work on a stopped runtime's data directory, and only "
        "a person runs them.",
    ]
    for c in commands:
        parts += [f"### `agentconnect {c.name}`", c.help, fence(c.usage)]
        if c.human:
            parts.append("Uses the **human token**: a person makes this decision.")
        if c.local:
            parts.append(
                "Runs **locally**, with no API and no token, on a stopped runtime's data "
                "directory: a person makes this decision."
            )
        if args := _arguments(c):
            parts.append(
                table(
                    ["Argument", "Required", "Description"],
                    [
                        (
                            f"`{(a.name or '').upper()}`",
                            "yes" if a.required else "no",
                            getattr(a, "help", None) or "",
                        )
                        for a in args
                    ],
                )
            )
        if opts := _options(c):
            parts.append(
                table(
                    ["Option", "Type", "Default", "Description"],
                    [
                        (
                            ", ".join(f"`{o}`" for o in [*o.opts, *o.secondary_opts]),
                            _option_type(o),
                            _option_default(o),
                            o.help or "",
                        )
                        for o in opts
                    ],
                )
            )
    return "\n\n".join(parts)


def render_cli_exit_codes() -> str:
    rows = [(str(code), f"`{name}`", meaning) for code, name, meaning in cli_support.EXIT_CODES]
    return "\n\n".join([NOTICE, table(["Code", "Constant", "Meaning"], rows)])


def render_cli_json() -> str:
    parts = [NOTICE]
    for label, shape in cli_json.SCHEMAS.items():
        parts.append(f"### `{label}`")
        note = cli_json.NOTES.get(label)
        if note is not None:
            parts.append(note)
        parts.append(fence(shape_text(shape)))
    return "\n\n".join(parts)


# -- local API ----------------------------------------------------------------------------


def render_api_routes() -> str:
    specs = api.ROUTE_SPECS
    summary = table(
        ["Method and path", "Token", "What it does"],
        [
            (
                f"`{s.method} {s.path}`",
                "**human**" if s.human else "api",
                first_sentence(s.summary),
            )
            for s in specs
        ],
    )
    parts = [
        NOTICE,
        summary,
        "Token: `api` routes accept either token. The routes marked human refuse "
        "the api token with `403 human_only`.",
    ]
    for s in specs:
        parts += [f"### `{s.method} {s.path}`", s.summary]
        parts.append(
            "Needs the **human token**." if s.human else "Accepts the api token or the human token."
        )
        if s.query:
            parts.append(f"Query: {s.query}")
        if s.request is not None:
            parts += ["Request body:", fence(shape_text(s.request))]
        if s.response is not None:
            parts += ["Response:", fence(shape_text(s.response))]
    return "\n\n".join(parts)


def render_api_errors() -> str:
    rows = [(str(status), f"`{code}`", meaning) for status, code, meaning in api.API_ERRORS]
    return "\n\n".join([NOTICE, table(["Status", "Code", "Meaning"], rows)])


# -- config -------------------------------------------------------------------------------


def _toml_type(annotation: object) -> str:
    if str(annotation).startswith("tuple"):
        return "array"
    names = {part.strip() for part in str(annotation).split("|")} - {"None"}
    if "bool" in names:
        return "boolean"
    if "int" in names:
        return "integer"
    return "string"


def render_config_keys() -> str:
    fields = {f.name: f for f in dataclasses.fields(config.Config)}
    rows = []
    for key in config.CONFIG_KEYS:
        rows.append(
            (
                f"`{key.key}`",
                key.kind or _toml_type(fields[key.field].type),
                key.default,
                f"`{key.env}`" if key.env else "none",
                key.doc,
            )
        )
    return "\n\n".join(
        [NOTICE, table(["Key", "Type", "Default", "Environment override", "Meaning"], rows)]
    )


def render_config_env() -> str:
    rows = [(f"`{k.env}`", f"`{k.key}`") for k in config.CONFIG_KEYS if k.env]
    rows += [(f"`{name}`", doc) for name, doc in config.CONFIG_ENV_EXTRA]
    return "\n\n".join(
        [
            NOTICE,
            table(["Variable", "Overrides"], rows),
            "A set variable wins over the file.",
        ]
    )


# -- safety settings ---------------------------------------------------------------------


def render_safety_settings() -> str:
    kinds: dict[type, str] = {bool: "boolean", int: "integer", str: "string"}
    rows = [
        (
            f"`{k.name}`",
            kinds[k.kind],
            config.shown_default(k.default),
            "yes" if k.per_sender else "no",
            k.doc,
        )
        for k in policy.KNOBS
    ]
    return "\n\n".join(
        [
            NOTICE,
            table(["Setting", "Type", "Default", "Per sender", "Meaning"], rows),
            "Each setting is also a key of `[policy]` in `config.toml` (`policy.<setting>`), "
            "which sets the default for every group.",
        ]
    )


# -- splicing -------------------------------------------------------------------------------


@dataclass(frozen=True)
class Section:
    name: str
    doc: str  # path relative to the repository root
    render: Callable[[], str]


SECTIONS: tuple[Section, ...] = (
    Section("cli", "docs/cli.md", render_cli_commands),
    Section("cli-exit-codes", "docs/cli.md", render_cli_exit_codes),
    Section("cli-json", "docs/cli.md", render_cli_json),
    Section("api-routes", "docs/api.md", render_api_routes),
    Section("api-errors", "docs/api.md", render_api_errors),
    Section("config-keys", "docs/config.md", render_config_keys),
    Section("config-env", "docs/config.md", render_config_env),
    Section("safety-settings", "docs/safety.md", render_safety_settings),
)


class MarkerError(ValueError):
    """A doc lacks the markers of a section, or has them out of order."""


def markers(name: str) -> tuple[str, str]:
    return f"<!-- generated:{name}:start -->", f"<!-- generated:{name}:end -->"


def splice(text: str, name: str, body: str) -> str:
    """``text`` with the content between the markers of ``name`` replaced."""
    start, end = markers(name)
    if text.count(start) != 1 or text.count(end) != 1:
        msg = f"expected exactly one {start} and one {end}"
        raise MarkerError(msg)
    first, last = text.index(start), text.index(end)
    if last < first:
        msg = f"{end} comes before {start}"
        raise MarkerError(msg)
    return f"{text[:first]}{start}\n\n{body.strip()}\n\n{text[last:]}"


def generate(root: Path = REPO) -> dict[Path, str]:
    """Each doc's new content, keyed by path."""
    docs: dict[Path, str] = {}
    for section in SECTIONS:
        path = root / section.doc
        text = docs.get(path) or path.read_text(encoding="utf-8")
        try:
            docs[path] = splice(text, section.name, section.render())
        except MarkerError as e:
            msg = f"{section.doc}: {e}"
            raise MarkerError(msg) from None
    return docs


def stale(root: Path = REPO) -> list[Path]:
    """The docs whose generated sections differ from what the code says."""
    return [
        path for path, text in generate(root).items() if path.read_text(encoding="utf-8") != text
    ]


def main(argv: Sequence[str] | None = None, root: Path = REPO) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    if args not in ([], ["--check"]):
        sys.stderr.write(__doc__ or "")
        return 2
    if args:
        paths = stale(root)
        for path in paths:
            sys.stderr.write(f"{path.relative_to(root)}: generated sections are stale\n")
        if paths:
            sys.stderr.write("Run `just docs-gen` and commit the result.\n")
        return 1 if paths else 0
    for path, text in generate(root).items():
        path.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
