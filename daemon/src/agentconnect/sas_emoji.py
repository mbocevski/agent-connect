def render_emoji(indices: list[int]) -> str:
    """The emoji row for the 7 six-bit SAS indices."""
    return " ".join(SAS_EMOJI[i][0] for i in indices)


def describe_emoji(indices: list[int]) -> str:
    """The same row as names, for terminals without emoji fonts."""
    return ", ".join(SAS_EMOJI[i][1] for i in indices)
